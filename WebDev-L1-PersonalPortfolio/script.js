function renderLucideIcons() {
  if (window.lucide && typeof window.lucide.createIcons === "function") {
    // If brand icons were omitted in active Lucide version, inject definitions
    if (window.lucide.icons) {
      if (!window.lucide.icons.Github) {
        window.lucide.icons.Github = [
          ["path", { "d": "M15 22v-4a4.8 4.8 0 0 0-1-3.5c3 0 6-2 6-5.5.08-1.25-.27-2.48-1-3.5.28-1.15.28-2.35 0-3.5 0 0-1 0-3 1.5-2.64-.5-5.36-.5-8 0C6 2 5 2 5 2c-.3 1.15-.3 2.35 0 3.5A5.403 5.403 0 0 0 4 9c0 3.5 3 5.5 6 5.5-.39.49-.68 1.05-.85 1.65-.17.6-.22 1.23-.15 1.85v4" }],
          ["path", { "d": "M9 18c-4.51 2-5-2-7-2" }]
        ];
      }
      if (!window.lucide.icons.Linkedin) {
        window.lucide.icons.Linkedin = [
          ["path", { "d": "M16 8a6 6 0 0 1 6 6v7h-4v-7a2 2 0 0 0-2-2 2 2 0 0 0-2 2v7h-4v-7a6 6 0 0 1 6-6z" }],
          ["rect", { "width": "4", "height": "12", "x": "2", "y": "9" }],
          ["circle", { "cx": "4", "cy": "4", "r": "2" }]
        ];
      }
    }
    try {
      window.lucide.createIcons();
    } catch (e) {
      console.warn("Lucide createIcons notice:", e);
    }
  }

  // Fallback: If any [data-lucide] tag was not converted into an SVG, convert it manually
  document.querySelectorAll("[data-lucide]").forEach((el) => {
    if (el.tagName.toLowerCase() !== "svg") {
      const iconName = el.getAttribute("data-lucide");
      if (iconName && LUCIDE_ICONS_SVG[iconName]) {
        const tempDiv = document.createElement("div");
        tempDiv.innerHTML = LUCIDE_ICONS_SVG[iconName];
        const svg = tempDiv.firstElementChild;
        if (svg) {
          if (el.className) {
            svg.setAttribute("class", el.className + " lucide lucide-" + iconName);
          }
          if (el.getAttribute("aria-hidden")) {
            svg.setAttribute("aria-hidden", el.getAttribute("aria-hidden"));
          }
          el.parentNode.replaceChild(svg, el);
        }
      }
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  // 1. Render all icons
  renderLucideIcons();

  // 2. Set dynamic footer year
  const yearEl = document.querySelector("#year");
  if (yearEl) {
    yearEl.textContent = new Date().getFullYear();
  }

  // 3. Mobile Navigation Toggle
  const menuToggle = document.querySelector(".menu-toggle");
  const navLinks = document.querySelector(".nav-links");

  if (menuToggle && navLinks) {
    const toggleMenu = (open) => {
      const shouldOpen = typeof open === "boolean" ? open : menuToggle.getAttribute("aria-expanded") !== "true";
      menuToggle.setAttribute("aria-expanded", String(shouldOpen));
      navLinks.classList.toggle("is-open", shouldOpen);
      if (shouldOpen) {
        document.body.style.overflow = "hidden";
      } else {
        document.body.style.overflow = "";
      }
    };

    menuToggle.addEventListener("click", () => {
      toggleMenu();
    });

    // Close menu when clicking any nav link
    navLinks.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        toggleMenu(false);
      });
    });

    // Close menu when clicking outside
    document.addEventListener("click", (e) => {
      if (
        menuToggle.getAttribute("aria-expanded") === "true" &&
        !navLinks.contains(e.target) &&
        !menuToggle.contains(e.target)
      ) {
        toggleMenu(false);
      }
    });

    // Close menu on Escape key
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
        toggleMenu(false);
        menuToggle.focus();
      }
    });
  }

  // 4. Header Background elevation on scroll
  const siteHeader = document.querySelector(".site-header");
  if (siteHeader) {
    const handleScroll = () => {
      if (window.scrollY > 30) {
        siteHeader.style.borderBottomColor = "rgba(255, 255, 255, 0.12)";
        siteHeader.style.background = "rgba(11, 13, 20, 0.95)";
      } else {
        siteHeader.style.borderBottomColor = "";
        siteHeader.style.background = "";
      }
    };
    window.addEventListener("scroll", handleScroll, { passive: true });
    handleScroll();
  }
});
